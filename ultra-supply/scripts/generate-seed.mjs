// Generates supabase/seed.sql from src/data/seed.ts (run: npm run seed:sql)
import { build } from 'esbuild';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL, fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outfile = join(mkdtempSync(join(tmpdir(), 'seed-')), 'seed.mjs');
await build({ entryPoints: [join(root, 'src/data/seed.ts')], bundle: true, format: 'esm', platform: 'node', outfile, alias: { '@': join(root, 'src') }, logLevel: 'error' });
const { seedCategories, seedProducts, seedPartners } = await import(pathToFileURL(outfile).href);

const s = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${s(JSON.stringify(v))}::jsonb`;
let sql = '-- Generated by scripts/generate-seed.mjs — placeholder catalogue data.\n\n';
for (const c of seedCategories)
  sql += `insert into public.categories (id, slug, name, description, image_url, sort_order) values (${s(c.id)}, ${s(c.slug)}, ${j(c.name)}, ${j(c.description)}, ${s(c.image_url)}, ${c.sort_order}) on conflict (id) do nothing;\n`;
sql += '\n';
for (const p of seedProducts)
  sql += `insert into public.products (id, slug, category_id, reference, name, description, specs, image_url, featured, published) values (${s(p.id)}, ${s(p.slug)}, ${s(p.category_id)}, ${s(p.reference)}, ${j(p.name)}, ${j(p.description)}, ${j(p.specs)}, ${s(p.image_url)}, ${p.featured}, ${p.published}) on conflict (id) do nothing;\n`;
sql += '\n';
for (const p of seedPartners)
  sql += `insert into public.partners (id, name, logo_url, website, sort_order, published) values (${s(p.id)}, ${s(p.name)}, null, null, ${p.sort_order}, true) on conflict (id) do nothing;\n`;
writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log('supabase/seed.sql written');
